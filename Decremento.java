public class Decremento {
   public static void main(String[] args) {

        int a = 5;

        System.out.printf("a = %d\n", a);
        System.out.printf("a = %d\n", a--);
        System.out.printf("a = %d\n", a);
        System.out.println(" primero utilizo el valor para imprimirlo y despues lo disminuyo");

        a = 5;

        System.out.printf("a = %d\n", a);
        System.out.printf("a = %d\n", --a);
        System.out.printf("a = %d\n", a);
        System.out.printf(" primero disminuyo el valor y despues lo utilizo para imprimirlo");

    }
}
